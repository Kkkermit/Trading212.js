// Generates src/types/api.generated.ts and src/http/endpoints.generated.ts from openapi/trading212.json.
// `--check` regenerates in memory and fails if the committed files differ.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { format, resolveConfig } from "prettier";

interface Schema {
	type?: string;
	format?: string;
	description?: string;
	enum?: string[];
	properties?: Record<string, Schema>;
	items?: Schema;
	additionalProperties?: Schema | boolean;
	$ref?: string;
	default?: unknown;
	example?: unknown;
}

interface Operation {
	summary?: string;
	description?: string;
	deprecated?: boolean;
	responses: Record<string, { description?: string }>;
}

interface Spec {
	info: { version: string; title: string };
	paths: Record<string, Record<string, Operation>>;
	components: { schemas: Record<string, Schema> };
}

interface Overrides {
	rateLimits: Record<string, { requests: number; periodSeconds: number; source: string }>;
}

const ROOT = resolve(import.meta.dirname, "..");
const SPEC_PATH = resolve(ROOT, "openapi/trading212.json");
const OVERRIDES_PATH = resolve(ROOT, "openapi/overrides.json");
const TYPES_OUT = resolve(ROOT, "src/types/api.generated.ts");
const ENDPOINTS_OUT = resolve(ROOT, "src/http/endpoints.generated.ts");

/** Our name for every operation. A path the spec adds that is not here fails generation until it is named. */
const NAMES: Record<string, string> = {
	"GET /api/v0/equity/account/summary": "getAccountSummary",
	"GET /api/v0/equity/positions": "listPositions",
	"GET /api/v0/equity/metadata/instruments": "listInstruments",
	"GET /api/v0/equity/metadata/exchanges": "listExchanges",
	"GET /api/v0/equity/orders": "listOrders",
	"GET /api/v0/equity/orders/{id}": "getOrder",
	"POST /api/v0/equity/orders/market": "placeMarketOrder",
	"POST /api/v0/equity/orders/limit": "placeLimitOrder",
	"POST /api/v0/equity/orders/stop": "placeStopOrder",
	"POST /api/v0/equity/orders/stop_limit": "placeStopLimitOrder",
	"DELETE /api/v0/equity/orders/{id}": "cancelOrder",
	"GET /api/v0/equity/history/orders": "listHistoricalOrders",
	"GET /api/v0/equity/history/dividends": "listDividends",
	"GET /api/v0/equity/history/transactions": "listTransactions",
	"GET /api/v0/equity/history/exports": "listReports",
	"POST /api/v0/equity/history/exports": "requestReport",
	"GET /api/v0/equity/pies": "listPies",
	"GET /api/v0/equity/pies/{id}": "getPie",
	"POST /api/v0/equity/pies": "createPie",
	"POST /api/v0/equity/pies/{id}": "updatePie",
	"DELETE /api/v0/equity/pies/{id}": "deletePie",
	"POST /api/v0/equity/pies/{id}/duplicate": "duplicatePie",
};

/** Writes that change nothing a user owns, so the live-trading switch does not guard them. */
const HARMLESS_WRITES = new Set(["requestReport"]);

const HEADER =
	"// Generated by scripts/generateApi.ts from openapi/trading212.json. Do not edit; run `npm run generate`.\n";

function readJson(path: string): unknown {
	return JSON.parse(readFileSync(path, "utf8"));
}

function docComment(text: string | undefined, indent = ""): string {
	if (!text?.trim()) return "";
	const lines = text
		.replaceAll("*/", "*\\/")
		.trim()
		.split("\n")
		.map((line) => line.trimEnd());
	if (lines.length === 1) return `${indent}/** ${lines[0] ?? ""} */\n`;
	return `${indent}/**\n${lines.map((line) => `${indent} *${line ? ` ${line}` : ""}`).join("\n")}\n${indent} */\n`;
}

function typeOf(schema: Schema): string {
	if (schema.$ref) return schema.$ref.split("/").pop() ?? "unknown";
	if (schema.enum) return `${schema.enum.map((value) => JSON.stringify(value)).join(" | ")} | (string & {})`;
	switch (schema.type) {
		case "string":
			return "string";
		case "integer":
		case "number":
			return "number";
		case "boolean":
			return "boolean";
		case "array":
			return `${schema.items ? wrapArrayItem(typeOf(schema.items)) : "unknown"}[]`;
		case "object":
			if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
				return `Record<string, ${typeOf(schema.additionalProperties)}>`;
			}
			return schema.properties ? inlineObject(schema) : "Record<string, unknown>";
		default:
			return "unknown";
	}
}

function wrapArrayItem(type: string): string {
	return type.includes("|") ? `(${type})` : type;
}

function inlineObject(schema: Schema): string {
	return `{ ${Object.entries(schema.properties ?? {})
		.map(([name, property]) => `${name}?: ${typeOf(property)} | null;`)
		.join(" ")} }`;
}

function propertyNote(schema: Schema): string | undefined {
	const notes: string[] = [];
	if (schema.description) notes.push(schema.description.trim());
	if (schema.format === "date-time") notes.push("ISO 8601 date and time.");
	if (schema.format === "int64" && !schema.description) notes.push("64-bit integer.");
	return notes.length ? notes.join("\n\n") : undefined;
}

function generateTypes(spec: Spec): string {
	let out = `${HEADER}// Every field is optional and may be null: the spec marks nothing as required, and the API omits fields freely.\n// Enums stay open so a value Trading 212 adds later still type-checks.\n\n`;
	for (const [name, schema] of Object.entries(spec.components.schemas).sort(([a], [b]) => a.localeCompare(b))) {
		out += docComment(schema.description);
		if (schema.enum) {
			out += `export type ${name} = ${typeOf(schema)};\n\n`;
			continue;
		}
		out += `export interface ${name} {\n`;
		for (const [property, propertySchema] of Object.entries(schema.properties ?? {})) {
			out += docComment(propertyNote(propertySchema), "\t");
			out += `\t${property}?: ${typeOf(propertySchema)} | null;\n`;
		}
		out += "}\n\n";
	}
	return out;
}

const RATE_LIMIT = /\*\*Rate limit:\*\*\s*(\d+)\s*req\s*\/\s*(?:(\d+)m)?(?:(\d+)s)?/;
const SCOPE = /Scope\(\s*([\w:]+)\s*\)/;

function generateEndpoints(spec: Spec, overrides: Overrides): { code: string; warnings: string[] } {
	const warnings: string[] = [];
	const entries: string[] = [];
	const seen = new Set<string>();
	for (const [path, operations] of Object.entries(spec.paths)) {
		for (const [method, operation] of Object.entries(operations)) {
			const key = `${method.toUpperCase()} ${path}`;
			const id = NAMES[key];
			if (!id) throw new Error(`The spec has ${key}, which has no name. Add it to NAMES in scripts/generateApi.ts.`);
			seen.add(key);
			const match = RATE_LIMIT.exec(operation.description ?? "");
			if (!match) throw new Error(`${key} has no rate limit in its description.`);
			let requests = Number(match[1]);
			let periodMs = (Number(match[2] ?? 0) * 60 + Number(match[3] ?? 0)) * 1000;
			const override = overrides.rateLimits[key];
			if (override) {
				if (requests === override.requests && periodMs === override.periodSeconds * 1000) {
					warnings.push(`The spec now agrees with the override for ${key}; delete it from overrides.json.`);
				}
				requests = override.requests;
				periodMs = override.periodSeconds * 1000;
			}
			const scope = SCOPE.exec(operation.responses["403"]?.description ?? "")?.[1] ?? null;
			const kind = method === "get" ? "read" : HARMLESS_WRITES.has(id) ? "write" : "trade";
			const definition = {
				id,
				method: method.toUpperCase(),
				path,
				scope,
				rateLimit: { requests, periodMs },
				kind,
				deprecated: operation.deprecated === true,
				summary: operation.summary ?? id,
			};
			entries.push(`\t${id}: ${JSON.stringify(definition)},`);
		}
	}
	for (const key of Object.keys(NAMES)) {
		if (!seen.has(key)) warnings.push(`${key} is no longer in the spec.`);
	}
	for (const key of Object.keys(overrides.rateLimits)) {
		if (!seen.has(key)) warnings.push(`The override for ${key} names an endpoint the spec no longer has.`);
	}
	entries.sort();
	const code = `${HEADER}import { type EndpointDefinition, freezeEndpoints } from "./endpoint";\n\nexport const SPEC_VERSION = ${JSON.stringify(spec.info.version)};\n\nconst DEFINITIONS = {\n${entries.join("\n")}\n} as const satisfies Record<string, EndpointDefinition>;\n\n/** Every endpoint in the spec, frozen so nothing at run time can turn a trade into a read. */\nexport const ENDPOINTS: typeof DEFINITIONS = freezeEndpoints(DEFINITIONS);\n\nexport type EndpointId = keyof typeof ENDPOINTS;\n`;
	return { code, warnings };
}

async function main(): Promise<void> {
	const check = process.argv.includes("--check");
	const spec = readJson(SPEC_PATH) as Spec;
	const overrides = readJson(OVERRIDES_PATH) as Overrides;
	const prettierConfig = (await resolveConfig(TYPES_OUT)) ?? {};
	const { code: endpoints, warnings } = generateEndpoints(spec, overrides);
	const files = [
		{ path: TYPES_OUT, code: await format(generateTypes(spec), { ...prettierConfig, parser: "typescript" }) },
		{ path: ENDPOINTS_OUT, code: await format(endpoints, { ...prettierConfig, parser: "typescript" }) },
	];
	for (const warning of warnings) console.warn(`warning: ${warning}`);
	let stale = false;
	for (const file of files) {
		let current = "";
		try {
			current = readFileSync(file.path, "utf8");
		} catch {
			// A missing file is simply out of date.
		}
		if (current === file.code) continue;
		if (check) {
			stale = true;
			console.error(`${file.path} is out of date. Run \`npm run generate\`.`);
		} else {
			writeFileSync(file.path, file.code);
			console.log(`wrote ${file.path}`);
		}
	}
	if (stale) process.exit(1);
}

await main();
